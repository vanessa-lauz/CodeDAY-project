public class Voluntario {
    String nome;
    String interesse;
    String formaDeAjuda;
    String localizacao;
    public Voluntario(String nome, String interesse, String formaDeAjuda, String localizacao) {
        this.nome = nome;
        this.interesse = interesse;
        this.formaDeAjuda = formaDeAjuda;
        this.localizacao = localizacao;
    }
}
